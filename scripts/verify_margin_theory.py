"""v6: verify the exact-boundary theory of the 1/e law and draw Fig. 5.

Usage (from the robosimu folder):
    python scripts/verify_margin_theory.py
Writes figures/v6/fig_v6_margin.png and reports/v6_margin_theory.md.
Pure NumPy + matplotlib; it does not run the simulator.  The 'observed'
column is copied from reports/v5_summary.md (ablation and delay report).
"""
from __future__ import annotations

import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from robosimu import margin as mg  # noqa: E402

DELAYS = [0.03, 0.06, 0.10, 0.15, 0.20]
L, N, T = 0.05, 8, 0.01
OBSERVED = [  # (variant, delay, delay used inside delta_eff, observed max overshoot %)
    ("delay term removed", 0.06, 0.001, 11.6),
    ("delay term removed", 0.15, 0.001, 41.9),
    ("delay under-reported x0.5", 0.03, 0.015, 3.9),
    ("delay under-reported x0.5", 0.06, 0.03, 3.7),
    ("delay under-reported x0.5", 0.10, 0.05, 3.3),
    ("delay under-reported x0.5", 0.15, 0.075, 3.0),
    ("delay under-reported x0.5", 0.20, 0.10, 2.5),
]


def compute():
    out = {"boundary_n8": mg.boundary_table(DELAYS, L, N, T),
           "boundary_n1": mg.boundary_table(DELAYS, L, 1, T)}
    lams = np.round(np.arange(0.2, 3.01, 0.05), 3)
    out["lams"] = lams
    out["os60"] = [mg.predicted_overshoot_pct(x, 0.06, L, N, T) for x in lams]
    out["os150"] = [mg.predicted_overshoot_pct(x, 0.15, L, N, T) for x in lams]
    out["ts60"] = [mg.predicted_settle_s(x, 0.06, L, N, T) for x in lams]
    rows = []
    for name, dl, used, obs in OBSERVED:
        s = mg.gain_scale_from_delay_report(dl, used, L, N, T)
        rows.append((name, dl, s, mg.predicted_overshoot_pct(s, dl, L, N, T), obs))
    out["ablation"] = rows
    return out


def draw(out, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.size": 9})
    fig, ax = plt.subplots(1, 3, figsize=(10.5, 3.2))
    d_ms = [r.delay_s * 1000 for r in out["boundary_n8"]]
    ax[0].plot(d_ms, [r.c_exact for r in out["boundary_n8"]], "o-", c="#8c3b1f", label="exact, n = 8")
    ax[0].plot(d_ms, [r.c_exact for r in out["boundary_n1"]], "s--", c="#3b6e8c", label="exact, n = 1")
    ax[0].axhline(1 / math.e, c="k", lw=0.8, ls=":", label="1/e")
    ax[0].set_ylim(0.34, 0.38); ax[0].set_xlabel("visual delay δ (ms)")
    ax[0].set_ylabel(r"$k^{*}\,\delta_{\mathrm{eff}}$"); ax[0].legend(frameon=False, fontsize=8)
    ax[0].set_title("(a) δ_eff places the law on the exact boundary", fontsize=9)
    lam = out["lams"]
    ax[1].plot(lam, out["os60"], c="#8c3b1f", label="60 ms")
    ax[1].plot(lam, out["os150"], c="#3b6e8c", ls="--", label="150 ms")
    ax[1].axvline(1.0, c="k", lw=0.8, ls=":")
    ax[1].set_xlabel(r"schema gain error $\lambda$ (eigenvalue of $J\hat J^{+}$)")
    ax[1].set_ylabel("predicted overshoot (%)"); ax[1].legend(frameon=False, fontsize=8)
    a2 = ax[1].twinx(); a2.plot(lam, out["ts60"], c="0.5", lw=0.8); a2.set_ylabel("settling time @60 ms (s)", color="0.4")
    ax[1].set_title("(b) λ>1 → overshoot, λ<1 → slow axis", fontsize=9)
    pr = [r[3] for r in out["ablation"]]; ob = [r[4] for r in out["ablation"]]
    cols = ["#8c3b1f" if "removed" in r[0] else "#3b6e8c" for r in out["ablation"]]
    ax[2].scatter(pr, ob, c=cols, s=22)
    m = max(max(pr), max(ob)) * 1.1
    ax[2].plot([0, m], [0, m], c="k", lw=0.8, ls=":")
    ax[2].set_xlabel("predicted max overshoot (%)"); ax[2].set_ylabel("observed in simulator (%)")
    ax[2].set_title("(c) ablations: theory vs 6-DoF plant", fontsize=9)
    fig.tight_layout(); os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, dpi=300); plt.close(fig)


def report(out, path):
    L_ = ["# v6 — exact-boundary theory of the 1/e law", "",
          "Generated by `scripts/verify_margin_theory.py` (pure NumPy, no simulator).", "",
          "## (a) δ_eff versus the exact sampled boundary (L = 50 ms, T = 10 ms)", "",
          "| δ (ms) | d (samples) | k* exact, n=8 (1/s) | k law (1/s) | k*/k_law | k*·δ_eff |",
          "|---|---|---|---|---|---|"]
    for r in out["boundary_n8"]:
        L_.append(f"| {r.delay_s*1000:.0f} | {r.d_samples} | {r.k_exact:.3f} | {r.k_law:.3f} | {r.ratio:.3f} | {r.c_exact:.4f} |")
    L_ += ["", "For n = 1 the exact gain is g* = d^d/(d+1)^(d+1); k*(dT + T/2) → 1/e.", "",
           "## (c) Ablations predicted from the gain multiplier alone", "",
           "| variant | δ (ms) | gain × | predicted max OS (%) | observed max OS (%) |", "|---|---|---|---|---|"]
    for name, dl, s, p, o in out["ablation"]:
        L_.append(f"| {name} | {dl*1000:.0f} | {s:.2f} | {p:.1f} | {o:.1f} |")
    L_ += ["", "Reading: the removed-delay ablation is predicted within 1–5 points by the",
           "scalar theory. With the delay under-reported, the observed overshoot at",
           "30–60 ms (3.7–3.9 %) is close to the full law's own (2.8–3.5 %): there it is",
           "dominated by body-schema error (λ_max slightly above 1), not by the report.",
           "At 150–200 ms the theory over-predicts, because the plant's joint-rate",
           "(0.6 rad/s) and acceleration (3 rad/s²) limits cap the speed. The scalar",
           "theory is a mechanism, not a full plant model."]
    open(path, "w", encoding="utf-8").write("\n".join(L_) + "\n")


if __name__ == "__main__":
    o = compute()
    draw(o, "figures/v6/fig_v6_margin.png")
    report(o, "reports/v6_margin_theory.md")
    print(open("reports/v6_margin_theory.md", encoding="utf-8").read())
